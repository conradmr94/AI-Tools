import time


class RateLimited(Exception):
    """Raised when a call would exceed the rate limit."""


class RateLimiter:
    """Token bucket: refills `rate` tokens per second, holds at most `burst`."""

    def __init__(self, rate, burst, clock=time.monotonic):
        self.rate = rate
        self.burst = burst
        self.clock = clock
        self.tokens = burst
        self.last = clock()

    def acquire(self):
        now = self.clock()
        self.tokens = min(self.burst, self.tokens + (now - self.last) * self.rate)
        self.last = now
        if self.tokens < 1:
            raise RateLimited()
        self.tokens -= 1
EOF

