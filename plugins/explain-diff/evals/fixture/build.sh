cat > client.py <<'EOF'
from config import DEFAULT_TIMEOUT_SECONDS
from ratelimit import RateLimited
from urls import build_url


class ApiClient:
    """Calls a JSON API through a transport function: transport(url, timeout) -> dict."""

    def __init__(self, base_url, transport, limiter):
        self.base_url = base_url
        self.transport = transport
        self.limiter = limiter

    def get(self, path):
        self.limiter.acquire()
        try:
            return self.transport(build_url(self.base_url, path), timeout=DEFAULT_TIMEOUT_SECONDS)
        except Exception:
            return None
EOF

