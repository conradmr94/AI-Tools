import unittest

from ratelimit import RateLimited, RateLimiter


class FrozenClock:
    def __init__(self):
        self.now = 0.0

    def __call__(self):
        return self.now


class RateLimiterTest(unittest.TestCase):
    def test_third_call_in_a_second_is_refused(self):
        limiter = RateLimiter(rate=2, burst=2, clock=FrozenClock())
        limiter.acquire()
        limiter.acquire()
        with self.assertRaises(RateLimited):
            limiter.acquire()

    def test_calls_within_the_limit_pass(self):
        limiter = RateLimiter(rate=2, burst=2, clock=FrozenClock())
        limiter.acquire()
        limiter.acquire()


if __name__ == "__main__":
    unittest.main()
EOF

